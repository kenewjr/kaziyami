package app.kaziyami.adapter

import kotlinx.serialization.json.Json
import kotlinx.serialization.json.jsonArray
import kotlinx.serialization.json.jsonObject
import kotlinx.serialization.json.jsonPrimitive
import org.junit.jupiter.api.Assertions.assertEquals
import org.junit.jupiter.api.Assertions.assertFalse
import org.junit.jupiter.api.Assertions.assertNotNull
import org.junit.jupiter.api.Assertions.assertTrue
import org.junit.jupiter.api.Test
import java.io.File
import java.util.zip.ZipFile

class KototoroPackagingTest {

    private val json = Json { ignoreUnknownKeys = true }

    @Test
    fun testKototoroApkDistributionArtifacts() {
        val rootDir = listOf(File("."), File("..")).firstOrNull { File(it, "settings.gradle.kts").exists() }
            ?: File(".")

        val repoDir = File(rootDir, "repo")
        val indexMinFile = File(repoDir, "index.min.json")

        // Ensure index exists (generated by build_apks / generate_repo_index)
        if (!indexMinFile.exists()) {
            val script = File(rootDir, "tools/generate_repo_index.py")
            val pb = ProcessBuilder("python", script.absolutePath, "--mode", "aniyomi")
            pb.directory(rootDir)
            pb.redirectErrorStream(true)
            pb.start().waitFor()
        }

        assertTrue(indexMinFile.exists(), "repo/index.min.json must exist for Kototoro repository distribution")

        val indexJson = json.parseToJsonElement(indexMinFile.readText()).jsonArray
        assertEquals(6, indexJson.size, "Kototoro distribution must index exactly 6 active production sources")

        val expectedSources = setOf(
            "Nekopoi", "Hentaimama", "Hanime",
            "Rule34Video", "Hanime1", "3xchina"
        )

        val indexedNames = mutableSetOf<String>()
        val apkDir = File(repoDir, "apk")

        for (item in indexJson) {
            val obj = item.jsonObject
            val displayName = obj["name"]?.jsonPrimitive?.content
            assertNotNull(displayName)
            assertTrue(displayName!!.startsWith("Kaziyami: "), "Display name must follow Kaziyami format: $displayName")

            val rawName = displayName.removePrefix("Kaziyami: ").trim()
            indexedNames.add(rawName)

            val apkName = obj["apk"]?.jsonPrimitive?.content
            assertNotNull(apkName)
            assertTrue(apkName!!.startsWith("kaziyami-") && apkName.endsWith(".apk"))

            val apkFile = File(apkDir, apkName)
            if (apkFile.exists()) {
                ZipFile(apkFile).use { zf ->
                    // 1. Must contain AndroidManifest.xml and classes.dex
                    assertNotNull(zf.getEntry("AndroidManifest.xml"), "$apkName must contain AndroidManifest.xml")
                    assertNotNull(zf.getEntry("classes.dex"), "$apkName must contain classes.dex")

                    // 2. Must NOT package host classes
                    val entries = zf.entries().asSequence().map { it.name }.toList()
                    assertFalse(entries.any { it.startsWith("okhttp3/") }, "$apkName must not bundle okhttp3 classes")
                    assertFalse(entries.any { it.startsWith("okio/") }, "$apkName must not bundle okio classes")
                    assertFalse(entries.any { it.startsWith("kotlin/") }, "$apkName must not bundle kotlin standard library")
                    assertFalse(entries.any { it.startsWith("android/") }, "$apkName must not bundle android framework classes")
                    assertFalse(entries.any { it.startsWith("org/jsoup/") }, "$apkName must not bundle jsoup classes")
                }
            }
        }

        assertEquals(expectedSources, indexedNames, "All 6 active sources must be indexed in Kototoro repository")
    }
}
